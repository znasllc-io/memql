// config.go -- the media server the environment names, and the boot work that records
// it (design section 7.1; plan Task 4).
//
// # All eight or none
//
// The media target is EIGHT variables read together: the provider, the control API's
// address, the address browsers connect to, how many seats the server carries, the API
// key pair rooms and passes are signed with, and the key pair the server signs its
// webhooks with. None set is a cluster without calls, which is every cluster until an
// operator adds a media server. A PARTIAL SET REFUSES BOOT, as integrations/voice's
// four LiveKit values do (app/integrations_voice.go): a server with no webhook key
// would admit people whose leaving nobody hears, and one with no public address would
// mint passes nobody can use, so a half-configured node is a configuration mistake to
// stop at once rather than a capability that fails later, one request at a time.
//
// # The provider is a recorded value, never a branch
//
// MEMQL_CALLS_MEDIA_PROVIDER says what runs the server (a container beside the local
// cluster, or a Hetzner server), and it is held to a closed set so a typo is a refusal.
// It is RECORDED on the media server row and nothing reads it to decide anything: the
// local cluster and a cloud one run the same code against the same kind of server,
// which is the environment-parity rule (docs/public/operate/environment-parity.md).
//
// # The bootstrap
//
// A node whose environment names a media server records it as ONE row,
// v1:calls:mediaServer:bootstrap, with its credentials SEALED into two global secrets
// the row names, and makes sure the key pepper exists. It runs on whichever nodes carry
// the configuration, at boot, and every replica booting with the same values must
// arrive at the same rows -- which a check-then-write cannot promise on its own. So the
// whole bootstrap runs under one write gate (memql.AcquireWriteGate, key
// "calls.media.bootstrap") with every read under it fresh (memql.ContextWithFreshRead):
// the second replica waits for the first to commit, reads what it wrote and finds
// nothing to do. A second boot of the same values WRITES NOTHING, no version of any of
// the four rows (operator_db_test.go asserts versions, not existence). What survives a
// retry or a crash part-way is whatever committed, and the next boot finishes it: every
// step compares before it writes.
//
// The environment is the truth for the server it names: a changed address, size,
// provider or credential is written as one new version, against the version it was
// decided from. The server's state is NOT the environment's: an operator's drain is
// kept. And the pepper is the environment's not at all: it is generated by the first
// boot that finds none and never written again (SecretKeyPepper says why).

// The eight variables of the media target.
const (
	EnvMediaProvider      = "MEMQL_CALLS_MEDIA_PROVIDER"
	EnvMediaAPIURL        = "MEMQL_CALLS_MEDIA_API_URL"
	EnvMediaPublicURL     = "MEMQL_CALLS_MEDIA_PUBLIC_URL"
	EnvMediaSeats         = "MEMQL_CALLS_MEDIA_SEATS"
	EnvMediaAPIKey        = "MEMQL_CALLS_MEDIA_API_KEY"
	EnvMediaAPISecret     = "MEMQL_CALLS_MEDIA_API_SECRET"
	EnvMediaWebhookKey    = "MEMQL_CALLS_MEDIA_WEBHOOK_KEY"
	EnvMediaWebhookSecret = "MEMQL_CALLS_MEDIA_WEBHOOK_SECRET"
)

// MediaEnvNames is the eight, in the order a refusal names the missing ones.
func MediaEnvNames() []string {
	return []string{
		EnvMediaProvider, EnvMediaAPIURL, EnvMediaPublicURL, EnvMediaSeats,
		EnvMediaAPIKey, EnvMediaAPISecret, EnvMediaWebhookKey, EnvMediaWebhookSecret,
	}
}

// mediaProviders is the closed set MEMQL_CALLS_MEDIA_PROVIDER may hold. See the file
// note: recorded on the row, never branched on.
var mediaProviders = []string{"docker-local", "hetzner"}

// minMediaSecretLength is the shortest signing secret accepted, for the API secret
// and the webhook secret alike. LiveKit signs passes and webhooks with HS256 under
// these, and integrations/voice holds its own LiveKit secret to the same 32
// characters; a webhook secret is what decides whether a "participant left" notice
// is believed, so it is held to the same floor as the secret that mints passes.
const minMediaSecretLength = 32

// BootstrapMediaServerID is the id of the media server the environment names.
const BootstrapMediaServerID = "bootstrap"

// bootstrapGateKey serializes the bootstrap across replicas (see the file note).
const bootstrapGateKey = "calls.media.bootstrap"

// pepperBytes is the size of the key pepper.
const pepperBytes = 32

// What each sealed secret says about itself where an operator meets it beside
// values they seeded themselves.
const (
	describeMediaCredential = "The calls media server's API key and secret, sealed from MEMQL_CALLS_MEDIA_API_KEY and MEMQL_CALLS_MEDIA_API_SECRET at boot. Change those values and restart to replace it."
	describeWebhookKey      = "The key pair the calls media server signs its webhooks with, sealed from MEMQL_CALLS_MEDIA_WEBHOOK_KEY and MEMQL_CALLS_MEDIA_WEBHOOK_SECRET at boot. Change those values and restart to replace it."
	describeKeyPepper       = "32 random bytes every calls key is digested under, generated once by the first boot that found none. Never replace it: every stored key digest depends on it."
)

// MediaConfig is the media server the environment names. It carries two secrets, so
// every way of printing it leaves them out (String, GoString, LogValue).
type MediaConfig struct {
	Provider  string // docker-local or hetzner: recorded, never branched on
	APIURL    string // the control API the engine calls
	PublicURL string // the address browsers connect to
	Seats     int

	APIKey, APISecret         string
	WebhookKey, WebhookSecret string
}

// String names the server and never its secrets.
func (c MediaConfig) String() string {
	return fmt.Sprintf("media server %s at %s (control %s, %d seats)", c.Provider, c.PublicURL, redactedURL(c.APIURL), c.Seats)
}

// GoString is String, so %#v cannot print the secrets either.
func (c MediaConfig) GoString() string { return c.String() }

// LogValue is what slog records for a config: the server, never its secrets.
func (c MediaConfig) LogValue() slog.Value {
	return slog.GroupValue(
		slog.String("provider", c.Provider),
		slog.String("publicUrl", c.PublicURL),
		slog.String("apiUrl", redactedURL(c.APIURL)),
		slog.Int("seats", c.Seats),
	)
}

// redactedURL is a URL with any user information taken out, for printing.
func redactedURL(raw string) string {
	u, err := url.Parse(raw)
	if err != nil {
		return "(unparseable)"
	}
	return u.Redacted()
}

// MediaConfigFromEnv reads the media target. All eight unset is (zero, false, nil): a
// cluster without calls. All eight set and usable is (config, true, nil). Anything else
// is an error naming the variables at fault and never a value, which the plug-in's
// factory returns so the node refuses to boot. Surrounding whitespace is not part of a
// value. A nil getenv reads the process environment.
func MediaConfigFromEnv(getenv func(string) string) (MediaConfig, bool, error) {
	if getenv == nil {
		getenv = os.Getenv
	}
	get := func(name string) string { return strings.TrimSpace(getenv(name)) }
	values := map[string]string{
		EnvMediaProvider:      get(EnvMediaProvider),
		EnvMediaAPIURL:        get(EnvMediaAPIURL),
		EnvMediaPublicURL:     get(EnvMediaPublicURL),
		EnvMediaSeats:         get(EnvMediaSeats),
		EnvMediaAPIKey:        get(EnvMediaAPIKey),
		EnvMediaAPISecret:     get(EnvMediaAPISecret),
		EnvMediaWebhookKey:    get(EnvMediaWebhookKey),
		EnvMediaWebhookSecret: get(EnvMediaWebhookSecret),
	}
	var missing []string
	for _, name := range MediaEnvNames() {
		if values[name] == "" {
			missing = append(missing, name)
		}
	}
	names := MediaEnvNames()
	if len(missing) == len(names) {
		return MediaConfig{}, false, nil
	}
	if len(missing) > 0 {
		return MediaConfig{}, false, fmt.Errorf(
			"calls: a media server is configured by all eight MEMQL_CALLS_MEDIA_* values or by none, and %d of %d are set; set %s, or unset them all",
			len(names)-len(missing), len(names), strings.Join(missing, ", "))
	}
	seats, err := strconv.Atoi(values[EnvMediaSeats])
	if err != nil {
		return MediaConfig{}, false, fmt.Errorf("calls: %s must be a whole number of seats", EnvMediaSeats)
	}
	cfg := MediaConfig{
		Provider:      values[EnvMediaProvider],
		APIURL:        values[EnvMediaAPIURL],
		PublicURL:     values[EnvMediaPublicURL],
		Seats:         seats,
		APIKey:        values[EnvMediaAPIKey],
		APISecret:     values[EnvMediaAPISecret],
		WebhookKey:    values[EnvMediaWebhookKey],
		WebhookSecret: values[EnvMediaWebhookSecret],
	}
	if err := cfg.validate(); err != nil {
		return MediaConfig{}, false, err
	}
	return cfg, true, nil
}

// validate holds a whole config to what a media server can use. Every refusal names the
// variable; none repeats a secret, and none repeats a URL, which may carry credentials.
func (c MediaConfig) validate() error {
	if !slices.Contains(mediaProviders, c.Provider) {
		return fmt.Errorf("calls: %s must be one of %s", EnvMediaProvider, strings.Join(mediaProviders, ", "))
	}
	if !urlWithHost(c.APIURL, "http", "https", "ws", "wss") {
		return fmt.Errorf("calls: %s must be an http, https, ws or wss URL with a host", EnvMediaAPIURL)
	}
	// Browsers reach the server over TLS only: a pass is a bearer credential, and
	// signalling in the clear would hand it to anyone on the path.
	if !urlWithHost(c.PublicURL, "wss", "https") {
		return fmt.Errorf("calls: %s must be a wss or https URL with a host", EnvMediaPublicURL)
	}
	if c.Seats <= 0 {
		return fmt.Errorf("calls: %s must be a positive number of seats", EnvMediaSeats)
	}
	if strings.TrimSpace(c.APIKey) == "" || strings.TrimSpace(c.WebhookKey) == "" {
		return fmt.Errorf("calls: %s and %s must be set", EnvMediaAPIKey, EnvMediaWebhookKey)
	}
	if len(c.APISecret) < minMediaSecretLength {
		return fmt.Errorf("calls: %s must be at least %d characters", EnvMediaAPISecret, minMediaSecretLength)
	}
	if len(c.WebhookSecret) < minMediaSecretLength {
		return fmt.Errorf("calls: %s must be at least %d characters", EnvMediaWebhookSecret, minMediaSecretLength)
	}
	return nil
}

func urlWithHost(raw string, schemes ...string) bool {
	u, err := url.Parse(raw)
	return err == nil && slices.Contains(schemes, u.Scheme) && u.Host != ""
}

// BootstrapResult says what a bootstrap wrote, for the boot log and a test. It names
// no value.
type BootstrapResult struct {
	ServerID       string
	ServerCreated  bool
	ServerUpdated  bool
	State          string
	SecretsWritten []string
}

// Bootstrap records the media server cfg names, seals its credentials and makes sure
// the key pepper exists, in that order, under the bootstrap gate (see the file note).
//
// THE ROW IS WRITTEN LAST. It names the credential's secret, so a failure part-way
// leaves at worst sealed secrets nothing names yet, never a row naming a secret that is
// not there; the next boot finishes the work.
func (i *Integration) Bootstrap(ctx context.Context, cfg MediaConfig) (BootstrapResult, error) {
	if err := cfg.validate(); err != nil {
		return BootstrapResult{}, err
	}
	pool, err := memql.ResolveWriteGatePool(i.gateDB, "calls: the media bootstrap", "the calls plug-in takes it from PluginContext.GateDB")
	if err != nil {
		return BootstrapResult{}, err
	}
	release, err := memql.AcquireWriteGate(ctx, pool, bootstrapGateKey)
	if err != nil {
		return BootstrapResult{}, fmt.Errorf("calls: take the media bootstrap's gate: %w", err)
	}
	defer release()
	fresh := memql.ContextWithFreshRead(ctx)
	result := BootstrapResult{ServerID: BootstrapMediaServerID}

	wrote, err := i.ensurePepper(fresh)
	if err != nil {
		return result, err
	}
	if wrote {
		result.SecretsWritten = append(result.SecretsWritten, SecretKeyPepper)
	}
	for _, sealed := range []struct {
		name, description string
		credential        MediaCredential
	}{
		{SecretMediaWebhook, describeWebhookKey, MediaCredential{Key: cfg.WebhookKey, Secret: cfg.WebhookSecret}},
		{SecretMediaBootstrap, describeMediaCredential, MediaCredential{Key: cfg.APIKey, Secret: cfg.APISecret}},
	} {
		wrote, err := i.ensureCredential(fresh, sealed.name, sealed.description, sealed.credential)
		if err != nil {
			return result, err
		}
		if wrote {
			result.SecretsWritten = append(result.SecretsWritten, sealed.name)
		}
	}

	want := MediaServer{
		ID: BootstrapMediaServerID, Provider: cfg.Provider, APIURL: cfg.APIURL, PublicURL: cfg.PublicURL,
		Seats: cfg.Seats, CredentialSecret: SecretMediaBootstrap,
	}
	prior, err := i.store.MediaServerByID(fresh, BootstrapMediaServerID)
	if err != nil {
		return result, err
	}
	switch {
	case prior == nil:
		if err := i.store.createMediaServer(fresh, want, i.now()); err != nil {
			return result, err
		}
		result.ServerCreated, result.State = true, "active"
	case !prior.sameTarget(want):
		if err := i.store.updateMediaServer(fresh, want, prior.Version, memql.VersionTimeAfter(prior.Version, i.now())); err != nil {
			return result, err
		}
		result.ServerUpdated, result.State = true, prior.State
	default:
		result.State = prior.State
	}
	return result, nil
}

// ensureCredential seals a media credential unless the stored one is already it. A
// stored one that cannot be decrypted (MEMQL_MASTER_KEY rotated under it) is replaced:
// the environment holds the value, so sealing it again under the current key repairs it.
func (i *Integration) ensureCredential(ctx context.Context, name, description string, want MediaCredential) (bool, error) {
	plaintext, err := want.seal()
	if err != nil {
		return false, err
	}
	have, err := i.store.resolveSecret(ctx, name)
	switch {
	case err == nil && have == plaintext:
		return false, nil
	case err == nil, memql.IsVariableNotFound(err), memql.IsSecretUndecryptable(err):
	default:
		return false, fmt.Errorf("calls: read the sealed secret %s: %w", name, err)
	}
	return true, i.store.sealSecret(ctx, name, plaintext, description)
}

// ensurePepper generates the key pepper when none is stored, and only then.
//
// A STORED PEPPER THAT CANNOT BE READ IS AN ERROR, NEVER A REASON TO WRITE ONE: it
// failed to decrypt (MEMQL_MASTER_KEY rotated under it) or holds something that is not
// 32 bytes, and replacing it would orphan every key's digest. An operator restores the
// key it was sealed under; calls stay off until then.
func (i *Integration) ensurePepper(ctx context.Context) (bool, error) {
	have, err := i.store.resolveSecret(ctx, SecretKeyPepper)
	switch {
	case err == nil:
		if _, err := decodePepper(have); err != nil {
			return false, err
		}
		return false, nil
	case memql.IsSecretUndecryptable(err):
		return false, fmt.Errorf("calls: the key pepper cannot be decrypted; it is never generated again, because every key digest depends on it, so restore the MEMQL_MASTER_KEY it was sealed under")
	case !memql.IsVariableNotFound(err):
		return false, fmt.Errorf("calls: read the key pepper: %w", err)
	}
	raw := make([]byte, pepperBytes)
	if _, err := io.ReadFull(i.random, raw); err != nil {
		return false, fmt.Errorf("calls: read randomness for the key pepper: %w", err)
	}
	return true, i.store.sealSecret(ctx, SecretKeyPepper, hex.EncodeToString(raw), describeKeyPepper)
}

// decodePepper reads the stored pepper. The error never repeats it.
func decodePepper(stored string) ([]byte, error) {
	raw, err := hex.DecodeString(strings.TrimSpace(stored))
	if err != nil || len(raw) != pepperBytes {
		return nil, fmt.Errorf("calls: the stored key pepper is not %d bytes of hex; it is never generated again, because every key digest depends on it", pepperBytes)
	}
	return raw, nil
}
