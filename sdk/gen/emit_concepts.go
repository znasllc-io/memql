// =============================================================================
// Concept + CDC-topic metadata emission (#2442 / A3)
//
// The generator resolves every construct's signature-bound concept to its
// canonical id (resolve.go). This file turns that + the full concept registry
// into MACHINE-READABLE, importable metadata -- not just a JSDoc comment:
//
//   - Concepts       : canonical concept id per stable SCREAMING_SNAKE key
//   - BoundConcepts  : generated construct wire-name -> its bound concept id
//   - CDCTopics      : full emitted CDC topic (graph.node.<action>.<concept>)
//   - CDCFilters     : subscription-filter form (node.<action>.<concept>;
//                      the backend prepends `graph.` per subscription kind)
//   - topicFor/filterFor : runtime composition for any concept id
//
// This is what replaces the SPA's hand-maintained
// src/lib/memql/generated/concepts.ts + subscriptionFilters.ts in A4 (#2443):
// the emitted CDCTopics/CDCFilters shape mirrors what those files export today.
// See component/events/pattern.go (BuildTopicWithConcept) + event.go
// (TopicGraphNode{Created,Updated,Deleted}) for the canonical topic grammar.
// =============================================================================

// cdcActions is the fixed, ordered set of graph node CDC actions. Order is
// part of the deterministic output contract.
var cdcActions = []string{"created", "updated", "deleted"}

var versionPrefixRe = regexp.MustCompile(`^v[0-9]+:`)

// emitConceptFiles builds the generated concept-metadata artifact(s): a Go
// file when goOut is set and a TS file when tsOut is set. importFrom is
// accepted for signature symmetry with Emit but unused -- the concept module
// is standalone constants (it augments nothing).
func emitConceptFiles(constructs []Construct, allConcepts []string, goOut, tsOut, importFrom string) []OutputFile {
	_ = importFrom
	var out []OutputFile
	if strings.TrimSpace(goOut) != "" {
		out = append(out, OutputFile{goOut, "generated_concepts.go", emitConceptsGo(constructs, allConcepts)})
	}
	if strings.TrimSpace(tsOut) != "" {
		out = append(out, OutputFile{tsOut, "generated_concepts.ts", emitConceptsTS(constructs, allConcepts)})
	}
	return out
}

// keyedConcepts returns the concept ids paired with their SCREAMING_SNAKE keys,
// sorted by key. Panics-free: a key collision (two distinct ids reducing to the
// same key) is disambiguated by appending the id's own tail so output stays a
// bijection AND deterministic.
func keyedConcepts(allConcepts []string) [][2]string {
	byKey := map[string]string{}
	var pairs [][2]string
	ids := append([]string(nil), allConcepts...)
	sort.Strings(ids)
	for _, id := range ids {
		key := conceptKey(id)
		if existing, dup := byKey[key]; dup && existing != id {
			// Extremely unlikely (would need two ids differing only in
			// camelCase vs colon boundaries). Disambiguate deterministically.
			key = key + "_" + screamingSnake(strings.ReplaceAll(id, ":", "_"))
		}
		byKey[key] = id
		pairs = append(pairs, [2]string{key, id})
	}
	sort.Slice(pairs, func(i, j int) bool { return pairs[i][0] < pairs[j][0] })
	return pairs
}

// boundPairs returns (constructName, conceptId) for every construct with a
// resolved bound concept, sorted by construct name.
func boundPairs(constructs []Construct) [][2]string {
	var pairs [][2]string
	for _, c := range constructs {
		if c.ConceptId != "" {
			pairs = append(pairs, [2]string{c.Name, c.ConceptId})
		}
	}
	sort.Slice(pairs, func(i, j int) bool { return pairs[i][0] < pairs[j][0] })
	return pairs
}

func emitConceptsGo(constructs []Construct, allConcepts []string) []byte {
	concepts := keyedConcepts(allConcepts)
	bound := boundPairs(constructs)

	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// Code generated by scripts/sdk-gen. DO NOT EDIT.\n")
	fmt.Fprintf(&buf, "// Source of truth: dsl/**/*.memql (concept @version/@namespace + construct signatures).\n\n")
	fmt.Fprintf(&buf, "package client\n\n")

	fmt.Fprintf(&buf, "// Concepts maps a stable SCREAMING_SNAKE key to a canonical concept id.\n")
	fmt.Fprintf(&buf, "var Concepts = map[string]string{\n")
	for _, p := range concepts {
		fmt.Fprintf(&buf, "\t%q: %q,\n", p[0], p[1])
	}
	fmt.Fprintf(&buf, "}\n\n")

	fmt.Fprintf(&buf, "// BoundConcepts maps a generated construct's wire name to the canonical\n")
	fmt.Fprintf(&buf, "// concept id its signature binds. Only constructs with a resolvable bound\n")
	fmt.Fprintf(&buf, "// concept appear.\n")
	fmt.Fprintf(&buf, "var BoundConcepts = map[string]string{\n")
	for _, p := range bound {
		fmt.Fprintf(&buf, "\t%q: %q,\n", p[0], p[1])
	}
	fmt.Fprintf(&buf, "}\n\n")

	fmt.Fprintf(&buf, "// CDCTopics maps <CONCEPT_KEY>_<ACTION> to the full emitted CDC topic\n")
	fmt.Fprintf(&buf, "// (graph.node.<action>.<concept>).\n")
	fmt.Fprintf(&buf, "var CDCTopics = map[string]string{\n")
	for _, p := range concepts {
		for _, a := range cdcActions {
			fmt.Fprintf(&buf, "\t%q: %q,\n", p[0]+"_"+strings.ToUpper(a), "graph.node."+a+"."+p[1])
		}
	}
	fmt.Fprintf(&buf, "}\n\n")

	fmt.Fprintf(&buf, "// CDCFilters maps <CONCEPT_KEY>_<ACTION> to the subscription-filter form\n")
	fmt.Fprintf(&buf, "// (node.<action>.<concept>); the backend prepends `graph.` per subscription kind.\n")
	fmt.Fprintf(&buf, "var CDCFilters = map[string]string{\n")
	for _, p := range concepts {
		for _, a := range cdcActions {
			fmt.Fprintf(&buf, "\t%q: %q,\n", p[0]+"_"+strings.ToUpper(a), "node."+a+"."+p[1])
		}
	}
	fmt.Fprintf(&buf, "}\n\n")

	fmt.Fprintf(&buf, "// TopicFor composes the full emitted CDC topic for a concept id + action\n")
	fmt.Fprintf(&buf, "// (\"created\" | \"updated\" | \"deleted\").\n")
	fmt.Fprintf(&buf, "func TopicFor(concept, action string) string { return \"graph.node.\" + action + \".\" + concept }\n\n")
	fmt.Fprintf(&buf, "// FilterFor composes the subscription-filter form (no `graph.` prefix).\n")
	fmt.Fprintf(&buf, "func FilterFor(concept, action string) string { return \"node.\" + action + \".\" + concept }\n")

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		fmt.Fprintf(os.Stderr, "WARN: gofmt failed for generated concepts: %v\n", err)
		return buf.Bytes()
	}
	return formatted
}

func emitConceptsTS(constructs []Construct, allConcepts []string) []byte {
	concepts := keyedConcepts(allConcepts)
	bound := boundPairs(constructs)

	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// Code generated by scripts/sdk-gen. DO NOT EDIT.\n")
	fmt.Fprintf(&buf, "// Source of truth: dsl/**/*.memql (concept @version/@namespace + construct signatures).\n\n")

	fmt.Fprintf(&buf, "/** Canonical concept ids, keyed by SCREAMING_SNAKE of <namespace>_<concept>. */\n")
	fmt.Fprintf(&buf, "export const Concepts = {\n")
	for _, p := range concepts {
		fmt.Fprintf(&buf, "  %s: %q,\n", p[0], p[1])
	}
	fmt.Fprintf(&buf, "} as const;\n")
	fmt.Fprintf(&buf, "export type ConceptKey = keyof typeof Concepts;\n")
	fmt.Fprintf(&buf, "export type ConceptId = (typeof Concepts)[ConceptKey];\n\n")

	fmt.Fprintf(&buf, "/** Per-construct bound concept: generated method name -> canonical concept id. */\n")
	fmt.Fprintf(&buf, "export const BoundConcepts = {\n")
	for _, p := range bound {
		fmt.Fprintf(&buf, "  %s: %q,\n", p[0], p[1])
	}
	fmt.Fprintf(&buf, "} as const;\n\n")

	fmt.Fprintf(&buf, "/** Full emitted CDC topics: graph.node.<action>.<concept>. */\n")
	fmt.Fprintf(&buf, "export const CDCTopics = {\n")
	for _, p := range concepts {
		for _, a := range cdcActions {
			fmt.Fprintf(&buf, "  %s: %q,\n", p[0]+"_"+strings.ToUpper(a), "graph.node."+a+"."+p[1])
		}
	}
	fmt.Fprintf(&buf, "} as const;\n\n")

	fmt.Fprintf(&buf, "/** Subscription filters: node.<action>.<concept> (the backend prepends `graph.`). */\n")
	fmt.Fprintf(&buf, "export const CDCFilters = {\n")
	for _, p := range concepts {
		for _, a := range cdcActions {
			fmt.Fprintf(&buf, "  %s: %q,\n", p[0]+"_"+strings.ToUpper(a), "node."+a+"."+p[1])
		}
	}
	fmt.Fprintf(&buf, "} as const;\n\n")

	fmt.Fprintf(&buf, "export type CDCAction = \"created\" | \"updated\" | \"deleted\";\n\n")
	fmt.Fprintf(&buf, "/** Compose the full emitted CDC topic for any concept id + action. */\n")
	fmt.Fprintf(&buf, "export const topicFor = (concept: string, action: CDCAction = \"created\"): string =>\n")
	fmt.Fprintf(&buf, "  `graph.node.${action}.${concept}`;\n\n")
	fmt.Fprintf(&buf, "/** Compose the subscription filter (no `graph.` prefix) for any concept id + action. */\n")
	fmt.Fprintf(&buf, "export const filterFor = (concept: string, action: CDCAction = \"created\"): string =>\n")
	fmt.Fprintf(&buf, "  `node.${action}.${concept}`;\n")

	return buf.Bytes()
}

// conceptKey reduces a canonical concept id to a stable SCREAMING_SNAKE key:
// strip the `v<n>:` version prefix, then SCREAMING_SNAKE each remaining
// colon-separated segment. `v1:cognition:audioOverride` -> COGNITION_AUDIO_OVERRIDE;
// `v1:cognition:turn:state` -> COGNITION_TURN_STATE.
func conceptKey(id string) string {
	s := versionPrefixRe.ReplaceAllString(id, "")
	var parts []string
	for _, seg := range strings.Split(s, ":") {
		if seg == "" {
			continue
		}
		parts = append(parts, screamingSnake(seg))
	}
	return strings.Join(parts, "_")
}

// screamingSnake converts a camelCase (or already-flat) identifier to
// SCREAMING_SNAKE_CASE. "audioOverride" -> "AUDIO_OVERRIDE"; "agent" -> "AGENT".
func screamingSnake(s string) string {
	var b strings.Builder
	runes := []rune(s)
	for i, r := range runes {
		if i > 0 && unicode.IsUpper(r) {
			prev := runes[i-1]
			if unicode.IsLower(prev) || unicode.IsDigit(prev) {
				b.WriteByte('_')
			}
		}
		b.WriteRune(unicode.ToUpper(r))
	}
	return b.String()
}
