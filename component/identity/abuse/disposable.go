// IsDisposable returns true if the email's domain is in the embedded
// disposable-email blocklist. The check is case-insensitive on the
// domain. Local-part is ignored.
//
// Returns false for malformed input (no @, empty domain) — the
// caller's email-format validator is responsible for rejecting those
// shapes earlier in the pipeline.
func IsDisposable(email string) bool {
	at := strings.LastIndex(email, "@")
	if at < 0 || at == len(email)-1 {
		return false
	}
	domain := strings.ToLower(strings.TrimSpace(email[at+1:]))
	if domain == "" {
		return false
	}
	_, ok := disposableDomains[domain]
	return ok
}
