// front of POST /auth/magic-link.
//
// The package is import-light by design — it depends on the parent
// component/identity package (for Config + AuditLogger) and the
// standard library, nothing else. Phase 6 may extend it with admin-UI
// hooks that read the rate-limiter state, but the core defenses stay
// in here.
