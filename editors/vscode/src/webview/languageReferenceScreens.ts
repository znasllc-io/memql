// The language reference page, built from the kit.
//
//   Language reference      Edition 2026 · Frozen · Grammar 2026.09-… · from local
//                                                 Copy grammar  Copy vocabulary
//   [ Search                                               ]
//   Grammar                                              126 productions
//   A file
//   <file> ::= <use>* <declaration>*
//   ...
//   Vocabulary                                               412 entries
//   construct  22
//   query  query <Concept> <name> { ... }
//     Read function: a bound concept, a filter and a projection.
//
// THE PAGE ANSWERS TWO QUESTIONS AND NEVER MIXES THEM UP. "What may I write?"
// is the grammar; "what does this name mean?" is the vocabulary. Both are
// GENERATED BY THE CLUSTER, so the head's meta says which language this is --
// the edition, its status, the grammar version -- and where it came from, in
// one line rather than a block of notes.
//
// SEARCH IS DRAWN BY THE HOST. The search box is a kit field; each keystroke
// reaches the host as an `input` message, and the page is patched in place
// (src/webview/ui/liveView.ts), which keeps the focused box and its caret while
// the lists narrow under it. Every item still carries the text it is matched
// by (`data-search`, built by state/languageReference.ts), and the rule is
// state/languageReference.ts's `matchesSearch` -- so what the tests exercise
// is what the page does.
//
// COPY TAKES THE WHOLE ARTIFACT, never the filtered view: both exist to be
// handed to a model, and a model given three productions out of a hundred and
// fifty writes MemQL shaped like the fragment it was shown. The acts' tooltip
// says so; the page does not.
//
// Every value goes through `escapeHtml` -- which matters more here than
// anywhere else in the tree, since half the words on this page are
// `<production>`, `@annotation` and `&&`.
//
// Deliberately free of `vscode` imports (cmd/memql-lsp/vscodeimportrule_test.go).

import { escapeHtml } from "@znasllc-io/memql-view-kit";

import {
  grammarSections,
  matchesSearch,
  productionCount,
  searchIndex,
  vocabularyByKind,
  type GrammarArtifact,
  type GrammarBlock,
  type LanguageIdentity,
  type LanguagePin,
  type VocabularyArtifact,
  type VocabularyEntry,
} from "../state/languageReference.js";
import { emptyState, head, notice, skeleton, subhead, textInput, type Act } from "./ui/kit.js";
import type { RegionParts } from "./ui/liveView.js";

/** What the page needs to draw itself. */
export interface LanguageReferenceInput {
  /** Which language this is, and on whose authority. */
  identity: LanguageIdentity;
  /**
   * This extension's own pin, for the case where a cluster was asked and did
   * not answer: the reader is still told the language their editor speaks.
   */
  pin?: LanguagePin | undefined;
  /** The cluster's grammar, when one has been read. */
  grammar?: GrammarArtifact | undefined;
  /** The cluster's vocabulary, when one has been read. */
  vocabulary?: VocabularyArtifact | undefined;
  /** A read is in flight. */
  loading: boolean;
  /** Why a read did not return what it was asked for, or "". */
  error: string;
  /** The search term the page holds. */
  search: string;
  /**
   * Whether this window can offer to pick a cluster. False in an untrusted
   * workspace, where `memql.clusters.select` is contributed but never
   * registered; the page offers workspace trust there instead.
   */
  offerSelectCluster: boolean;
}

/** The message the page posts when a copy act is pressed. */
export const COPY_GRAMMAR = "copyGrammar";
/** The message the page posts when the vocabulary copy act is pressed. */
export const COPY_VOCABULARY = "copyVocabulary";
/** The search box's field name: the runtime posts `{ type: "input", field, value }`. */
export const SEARCH_FIELD = "search";
/** The message the page posts from "Select a cluster". */
export const SELECT_CLUSTER = "selectCluster";
/** The message the page posts from "Manage workspace trust", in an untrusted window. */
export const MANAGE_TRUST = "manageTrust";
/**
 * The message the page posts from "Try again".
 *
 * A CONSTANT like the others, and for the reason they are: the act that emits
 * it and the handler that answers it live in different modules, and a pair of
 * bare literals that must agree is a pair that can silently disagree.
 */
export const RELOAD = "reload";

/** The head's one line: which language, and whose word it is. */
export function identityMeta(identity: LanguageIdentity): string {
  const parts = [
    identity.edition === "" ? "Edition not stated" : `Edition ${identity.edition}`,
    identity.status === "" ? "" : identity.status.charAt(0).toUpperCase() + identity.status.slice(1),
    identity.grammarVersion === "" ? "" : `Grammar ${identity.grammarVersion}`,
    identity.source === "cluster" ? `from ${identity.cluster}` : "built in",
  ];
  return parts.filter((part) => part !== "").join(" · ");
}

/** The page, whole. No action bar: nothing here changes anything. */
export function languageReferenceParts(input: LanguageReferenceInput): RegionParts {
  const asideActs: Act[] = [];
  if (input.grammar !== undefined) {
    asideActs.push({ act: COPY_GRAMMAR, label: "Copy grammar", title: "Copies the whole grammar, whatever the search shows" });
  }
  if (input.vocabulary !== undefined) {
    asideActs.push({ act: COPY_VOCABULARY, label: "Copy vocabulary", title: "Copies the whole vocabulary, whatever the search shows" });
  }
  const headHtml = head({ title: "Language reference", meta: identityMeta(input.identity), asideActs });
  return { head: headHtml, body: bodyHtml(input), actions: "" };
}

/** The page as one string, for the tests and anything else that reads it whole. */
export function renderLanguageReferencePage(input: LanguageReferenceInput): string {
  const parts = languageReferenceParts(input);
  return parts.head + parts.body;
}

function bodyHtml(input: LanguageReferenceInput): string {
  const { grammar, vocabulary } = input;
  if (input.identity.source === "extension") return notConnectedHtml(input);
  if (input.loading) {
    return skeleton({ shape: "list", rows: 8, label: `Reading the grammar and vocabulary from ${input.identity.cluster}` });
  }
  let out = editionNote(input);
  const missing = [grammar === undefined ? "a grammar" : "", vocabulary === undefined ? "a vocabulary" : ""].filter(
    (part) => part !== "",
  );
  if (missing.length > 0) {
    out += notice({
      tone: "error",
      line: `${input.identity.cluster} didn't return ${missing.join(" or ")}.`,
      next: input.error === "" ? undefined : input.error,
      acts: [{ act: RELOAD, label: "Try again" }],
    });
  }
  if (grammar === undefined && vocabulary === undefined) return out + pinFallbackHtml(input.pin);
  out += `<div class="lr-search">${textInput({
    field: SEARCH_FIELD,
    id: "lr-search",
    value: input.search,
    placeholder: "Search",
  })}</div>`;
  if (grammar !== undefined) out += grammarHtml(grammar, input.search);
  if (vocabulary !== undefined) out += vocabularyHtml(vocabulary, input.search);
  return out;
}

/** Said only when the cluster and this editor speak different editions. */
function editionNote(input: LanguageReferenceInput): string {
  const pin = input.pin;
  const cluster = input.identity;
  if (pin === undefined || pin.edition === "" || cluster.edition === "" || pin.edition === cluster.edition) return "";
  return `<p class="mq-empty-line lr-note">${escapeHtml(
    `${cluster.cluster} speaks edition ${cluster.edition}; this editor speaks ${pin.edition}.`,
  )}</p>`;
}

/**
 * What the extension knows, for a page that asked a cluster and got nothing:
 * the language its own completion and diagnostics speak right now.
 */
function pinFallbackHtml(pin: LanguagePin | undefined): string {
  if (pin === undefined || pin.edition === "") return "";
  const status = pin.status === "" ? "" : ` (${pin.status})`;
  const grammar = pin.grammarVersion === "" ? "" : `, grammar ${pin.grammarVersion}`;
  return `<p class="mq-empty-line lr-note">${escapeHtml(
    `This editor speaks edition ${pin.edition}${status}${grammar}.`,
  )}</p>`;
}

/** No cluster: one sentence, and the act that fixes it. */
function notConnectedHtml(input: LanguageReferenceInput): string {
  if (input.offerSelectCluster) {
    return emptyState({
      line: "Connect to a cluster to see its grammar and vocabulary.",
      acts: [{ act: SELECT_CLUSTER, label: "Select a cluster", tone: "secondary" }],
    });
  }
  return emptyState({
    line: "Trust this workspace to connect to a cluster.",
    acts: [{ act: MANAGE_TRUST, label: "Manage workspace trust", tone: "secondary" }],
  });
}

/** "12 productions", or "3 of 12 productions" while a search narrows it. */
function countText(shown: number, total: number, noun: string, searching: boolean): string {
  return searching ? `${shown} of ${total} ${noun}` : `${total} ${noun}`;
}

function hiddenAttr(visible: boolean): string {
  return visible ? "" : " hidden";
}

/** The grammar: the cluster's own sections, its own productions. */
function grammarHtml(grammar: GrammarArtifact, search: string): string {
  const sections = grammarSections(grammar.content);
  const total = productionCount(sections);
  const searching = search.trim() !== "";
  let shownProductions = 0;
  let shownItems = 0;
  const groups = sections
    .map((section) => {
      let visibleHere = 0;
      const blocks = section.blocks
        .map((block) => {
          const index = blockIndex(block);
          const visible = matchesSearch(index, search);
          if (visible) {
            visibleHere += 1;
            shownItems += 1;
            if (block.name !== "") shownProductions += 1;
          }
          return blockHtml(block, index, visible);
        })
        .join("");
      const title = section.title === "" ? "" : `<h3 class="lr-group-head">${escapeHtml(section.title)}</h3>`;
      return `<section class="lr-group"${hiddenAttr(visibleHere > 0)}>${title}${blocks}</section>`;
    })
    .join("");
  const format = grammar.format === "" ? "" : `${grammar.format.toUpperCase()} · `;
  const none =
    searching && shownItems === 0
      ? `<p class="mq-empty-line">${escapeHtml(`Nothing in the grammar matches "${search.trim()}".`)}</p>`
      : "";
  return (
    `<div class="lr-scope" data-scope="grammar">` +
    subhead("Grammar", `${format}${countText(shownProductions, total, "productions", searching)}`) +
    groups +
    none +
    `</div>`
  );
}

function blockIndex(block: GrammarBlock): string {
  return searchIndex([block.name, block.lines.join("\n")]);
}

/**
 * One production, or one of the cluster's own comments. Both are searchable;
 * only a production counts toward "productions" (`data-tally`), so a term that
 * matches only the header comment never reads "1 of 126 productions".
 */
function blockHtml(block: GrammarBlock, index: string, visible: boolean): string {
  const tally = block.name === "" ? "" : " data-tally";
  return `<pre class="lr-production" data-search="${escapeHtml(index)}"${tally}${hiddenAttr(visible)}>${escapeHtml(
    block.lines.join("\n"),
  )}</pre>`;
}

/** The vocabulary, grouped by the kinds the cluster named. */
function vocabularyHtml(vocabulary: VocabularyArtifact, search: string): string {
  const searching = search.trim() !== "";
  let shown = 0;
  const groups = vocabularyByKind(vocabulary)
    .map((group) => {
      let visibleHere = 0;
      const entries = group.entries
        .map((entry) => {
          const index = searchIndex([entry.name, entry.signature, entry.description, entry.kind]);
          const visible = matchesSearch(index, search);
          if (visible) visibleHere += 1;
          return entryHtml(entry, index, visible);
        })
        .join("");
      shown += visibleHere;
      // A group's own count follows the search too: left at its total beside
      // one visible entry it reads as the number of matches.
      const count = searching ? `${visibleHere} of ${group.entries.length}` : String(group.entries.length);
      return (
        `<section class="lr-group"${hiddenAttr(visibleHere > 0)}>` +
        `<h3 class="lr-group-head">${escapeHtml(group.kind)} <span class="mq-head-meta">${escapeHtml(count)}</span></h3>` +
        `${entries}</section>`
      );
    })
    .join("");
  const none =
    searching && shown === 0
      ? `<p class="mq-empty-line">${escapeHtml(`Nothing in the vocabulary matches "${search.trim()}".`)}</p>`
      : "";
  return (
    `<div class="lr-scope" data-scope="vocabulary">` +
    subhead("Vocabulary", countText(shown, vocabulary.entries.length, "entries", searching)) +
    groups +
    none +
    `</div>`
  );
}

/** One vocabulary entry: the name, how it is written, what it means. */
function entryHtml(entry: VocabularyEntry, index: string, visible: boolean): string {
  const tier = tierHtml(entry.tier);
  const signature = entry.signature === "" ? "" : `<code class="lr-signature">${escapeHtml(entry.signature)}</code>`;
  const description = entry.description === "" ? "" : `<p class="mq-field-hint lr-desc">${escapeHtml(entry.description)}</p>`;
  return (
    `<div class="lr-entry" data-search="${escapeHtml(index)}" data-tally${hiddenAttr(visible)}>` +
    `<div class="lr-entry-head"><code class="lr-name">${escapeHtml(entry.name)}</code>${signature}${tier}</div>` +
    `${description}</div>`
  );
}

/**
 * A catalog function's tier, as a word with its meaning in the tooltip. The
 * cluster sends a letter ("P" when the call lowers to SQL, "M" when it runs in
 * process); an unrecognised one is shown as sent rather than guessed at.
 */
function tierHtml(tier: string): string {
  if (tier === "") return "";
  const [word, meaning] =
    tier === "P" ? ["SQL", "Lowers to SQL in the database"] : tier === "M" ? ["In process", "Runs in the engine"] : [tier, ""];
  const title = meaning === "" ? "" : ` title="${escapeHtml(meaning)}"`;
  return `<span class="lr-tier mq-head-meta"${title}>${escapeHtml(word)}</span>`;
}

